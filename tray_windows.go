package main

import (
	"fmt"
	"log"

	"github.com/getlantern/systray"
)

var (
	trayReady = make(chan bool)
)

// InitTray 初始化系统托盘
func InitTray() {
	systray.Run(onReady, onExit)
}

// onReady 托盘准备就绪时调用
func onReady() {
	// 设置托盘图标和提示
	systray.SetIcon(getIcon())
	systray.SetTitle("兴宜街道红旗路输入法切换工具")
	systray.SetTooltip("兴宜街道红旗路输入法切换工具\nWin+J: 英文\nWin+K: 中文")

	// 创建菜单项
	mStatus := systray.AddMenuItem("✅ 运行中", "当前状态")
	mStatus.Disable()

	systray.AddSeparator()

	mInfo := systray.AddMenuItem("快捷键说明", "查看快捷键")
	mInfo.Disable()

	mWinJ := systray.AddMenuItem("  Win+J - 英文输入法", "切换到英文")
	mWinJ.Disable()

	mWinK := systray.AddMenuItem("  Win+K - 中文输入法", "切换到中文")
	mWinK.Disable()

	systray.AddSeparator()

	mQuit := systray.AddMenuItem("退出", "退出程序")

	// 通知主程序托盘已就绪
	close(trayReady)

	// 处理菜单点击事件
	go func() {
		for range mQuit.ClickedCh {
			fmt.Println("用户从托盘退出程序")
			systray.Quit()
			return
		}
	}()
}

// onExit 托盘退出时调用
func onExit() {
	// 清理键盘钩子
	StopKeyboardHook()
	fmt.Println("程序已退出")
}

